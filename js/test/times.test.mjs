// Compares js/src/times.js with the Python reference (py/src/times.py). The golden values below were made by
// running times.py itself under python3, with its `js.Intl` stubbed by zoneinfo (same answers as Intl for these
// dates): America/Los_Angeles, Europe/London, Australia/Lord_Howe (30-minute daylight saving), UTC and
// Asia/Kolkata; times in the spring-forward gap and the fall-back overlap, month ends, leap years, bad input.
import test from "node:test";
import assert from "node:assert/strict";
import { REPEATS, validZone, toLocal, fromLocal, nextTime, wallClock, fromWallClock } from "../src/times.js";

const attempt = (f) => { try { return f(); } catch (e) { return { error: e.message }; } };

test("REPEATS", () => assert.deepEqual(REPEATS, ["once", "daily", "weekly", "monthly"]));

test("validZone", () => {
  for (const z of ["America/Los_Angeles", "Europe/London", "Australia/Lord_Howe", "UTC"]) assert.equal(validZone(z), true, z);
  for (const z of ["Not/A_Zone", "", "Mars/Olympus", "America/Los Angeles"]) assert.equal(validZone(z), false, z);
  assert.equal(validZone("Not/A_Zone"), false); // a bad zone isn't kept
});

test("toLocal matches Python", () => {
  for (const [ms, zone, want] of G.toLocal) assert.equal(toLocal(ms, zone), want, `${ms} ${zone}`);
});

test("fromLocal matches Python (gaps, overlaps, strptime strictness, error texts)", () => {
  for (const [text, zone, want] of G.fromLocal) assert.deepEqual(attempt(() => fromLocal(text, zone)), want, `${JSON.stringify(text)} ${zone}`);
});

test("nextTime matches Python (daily/weekly across daylight saving, monthly from month ends)", () => {
  for (const [repeat, zone, chain] of G.nextTime)
    chain.slice(1).forEach((want, i) => assert.equal(nextTime(chain[i], repeat, zone), want, `${repeat} ${zone} ${chain[i]}`));
  for (const [repeat, want] of G.badRepeat) assert.deepEqual(attempt(() => nextTime(0, repeat, "UTC")), want);
});

test("spot checks", () => {
  assert.equal(toLocal(fromLocal("2026-01-31 09:00", "America/Los_Angeles"), "America/Los_Angeles"), "2026-01-31 09:00");
  let t = fromLocal("2026-01-31 09:00", "UTC"), seen = [];
  for (let i = 0; i < 3; i++) seen.push(toLocal(t = nextTime(t, "monthly", "UTC"), "UTC"));
  assert.deepEqual(seen, ["2026-02-28 09:00", "2026-03-28 09:00", "2026-04-28 09:00"]);
  assert.equal(toLocal(fromLocal("2026-03-08 02:30", "America/Los_Angeles"), "America/Los_Angeles"), "2026-03-08 01:30"); // in the gap: as Python does
  assert.equal(fromLocal("2026-1-5 9:00", "UTC"), Date.UTC(2026, 0, 5, 9));
  assert.equal(fromWallClock({ year: 2026, month: 12, day: 32, hour: 0, minute: 0, second: 0 }, "UTC"), Date.UTC(2027, 0, 1));
  assert.deepEqual(wallClock(Date.UTC(2026, 6, 1, 12), "Europe/London"), { month: 7, day: 1, year: 2026, hour: 13, minute: 0, second: 0, literal: NaN });
  assert.equal(attempt(() => fromLocal(null, "UTC")).error, "Write the time as YYYY-MM-DD HH:MM, not None");
});

